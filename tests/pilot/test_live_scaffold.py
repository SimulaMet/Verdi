class FakeLiveCaller:
    """ModelCaller that serves the recorded tape and records each call.

    ``quarantine_tasks``: task_ids whose completion is deliberately invalid.
    """

    def __init__(self, tape: list[str], quarantine_tasks: set[str] | None = None):
        self._tape = list(tape)
        self.quarantine_tasks = quarantine_tasks or set()
        self.call_count = 0
        self.last_result: ModelResult | None = None
        self.last_prompt: str | None = None
        self.last_kwargs: dict[str, object] | None = None

    async def generate_structured(
        self,
        messages: list[dict[str, str]],
        *,
        response_format_json: bool = False,
        temperature: float = 0.0,
        max_tokens: int | None = None,
    ) -> ModelResult:
        self.call_count += 1
        prompt = messages[0]["content"]
        self.last_prompt = prompt
        self.last_kwargs = {
            "response_format_json": response_format_json,
            "temperature": temperature,
            "max_tokens": max_tokens,
        }
        quarantine = any(f"Task {tid} (" in prompt for tid in self.quarantine_tasks)
        content = "not json" if quarantine else self._tape.pop(0)
        result = ModelResult(
            content=content,
            request_id=f"live-{self.call_count - 1}",
            model="fake-live-qwen",
            trace_id=f"trace-fake-{self.call_count - 1}",
            usage={"prompt_tokens": 12, "completion_tokens": 7},
        )
        self.last_result = result
        return result


def _tape_in_dispatch_order() -> list[str]:
    """Recorded completion per dispatch, in dispatch order."""
    driver = PilotDriver(MAIN_CHECKOUT)
    loaded = driver.loader.load()
    scheduler = SeededScheduler(loaded.t0_state.seed)
    dispatch = _precompute_dispatch(scheduler, loaded.tape, loaded.t0_state)
    tasks_by_id = {t.task_id: t for tick_tasks in loaded.tape for t in tick_tasks}
    return [model_output_for(tasks_by_id[tid].action_type) for _, tid, _ in dispatch]


class _BareCaller:
    """ModelCaller with the last_result/last_prompt contract, no adapter."""

    def __init__(self, inner: FakeLiveCaller):
        self._inner = inner
        self.call_count = 0
        self.last_result: ModelResult | None = None
        self.last_prompt: str | None = None

    async def generate_structured(self, messages, *, response_format_json=False,
                                  temperature=0.0, max_tokens=None) -> ModelResult:
        self.call_count += 1
        self.last_prompt = messages[0]["content"]
        result = await self._inner.generate_structured(
            messages,
            response_format_json=response_format_json,
            temperature=temperature,
            max_tokens=max_tokens,
        )
        self.last_result = result
        return result


def _read_tape(capture_dir: Path) -> list[dict]:
    lines = (capture_dir / "live_tape.jsonl").read_text().splitlines()
    return [json.loads(line) for line in lines]


def _make_fake(tape: list[str], quarantine: set[str] | None = None) -> FakeLiveCaller:
    return FakeLiveCaller(tape, quarantine)


@pytest.fixture(scope="module")
def baseline():
    return PilotDriver(MAIN_CHECKOUT).run()


def test_live_run_matches_recorded_baseline(tmp_path, baseline) -> None:
    """Fake serving the recorded tape => identical ledger, one call per dispatch."""
    tape = _tape_in_dispatch_order()
    fake = _make_fake(tape)
    caller = _BareCaller(fake)
    pilot = PilotDriver(MAIN_CHECKOUT, model=caller, live_capture_dir=tmp_path).run()

    assert fake.call_count == len(tape)
    assert len(pilot.log.events) == len(baseline.log.events)
    assert pilot.final_state.state_hash == baseline.final_state.state_hash
    assert pilot.quarantined == []

    rows = _read_tape(tmp_path)
    assert len(rows) == fake.call_count
    for i, row in enumerate(rows):
        for field in TAPE_FIELDS:
            assert field in row, f"missing field {field!r} in tape row {i}"
        assert row["seq"] == i
        assert row["prompt"].startswith("[prompt:")
        assert row["response_raw"]
        assert row["usage"]
        assert row["quarantined"] is False
        assert row["quarantine_reason"] is None
        assert row["parsed_action"] is not None
    # the driver captured the exact prompt the policy sent to the model
    assert fake.last_prompt == rows[-1]["prompt"]
    assert fake.last_kwargs == {
        "response_format_json": True,
        "temperature": 0.0,
        "max_tokens": None,
    }

    meta = json.loads((tmp_path / "live_run_meta.json").read_text())
    assert meta["call_count"] == fake.call_count
    assert meta["quarantined_count"] == 0
    assert meta["temperature"] == 0.0


def test_quarantined_live_call_is_audited_not_dropped(tmp_path) -> None:
    """One invalid completion => quarantined event, tape line, run completes."""
    driver = PilotDriver(MAIN_CHECKOUT)
    loaded = driver.loader.load()
    scheduler = SeededScheduler(loaded.t0_state.seed)
    dispatch = _precompute_dispatch(scheduler, loaded.tape, loaded.t0_state)
    assert dispatch, "dispatch must not be empty"
    target_tick, target_task, target_actor = dispatch[1]
    tasks_by_id = {t.task_id: t for tick_tasks in loaded.tape for t in tick_tasks}
    tape = [
        model_output_for(tasks_by_id[tid].action_type) if tid != target_task else None
        for _, tid, _ in dispatch
    ]
    # The quarantined dispatch must NOT consume a tape entry.
    tape = [out for out in tape if out is not None]

    fake = _make_fake(tape, {target_task})
    caller = _BareCaller(fake)
    pilot = PilotDriver(MAIN_CHECKOUT, model=caller, live_capture_dir=tmp_path).run()

    assert fake.call_count == len(dispatch)
    assert any(t == target_task for t, _ in pilot.quarantined)
    reason = next(r for t, r in pilot.quarantined if t == target_task)
    assert reason.startswith("invalid json")

    # audited, not dropped: an event for the quarantined dispatch exists
    step = next(
        (s for s in pilot.tape_steps if s.action.task_id == target_task), None
    )
    assert step is not None
    assert step.action.action_kind == "unknown"
    assert step.action.actor_id == target_actor
    assert step.validation.accepted is False
    assert step.validation.blocked_by == "policy:quarantine"
    event = pilot.log.events[
        [s.action.task_id for s in pilot.tape_steps].index(target_task)
    ]
    assert event.kind == "action_rejected"
    assert event.payload.get("blocked_by") == "policy:quarantine"

    rows = _read_tape(tmp_path)
    assert len(rows) == fake.call_count
    qrow = next(r for r in rows if r["task_id"] == target_task)
    assert qrow["quarantined"] is True
    assert qrow["response_raw"] == "not json"
    assert qrow["parsed_action"] is None
    assert qrow["quarantine_reason"]
    assert qrow["prompt"].startswith("[prompt:")

    pilot.log.verify()
    meta = json.loads((tmp_path / "live_run_meta.json").read_text())
    assert meta["quarantined_count"] == 1
    assert meta["call_count"] == fake.call_count


