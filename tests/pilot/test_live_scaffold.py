"""L1 live-capture scaffold tests (ADR-010) — NO NETWORK.

A FakeLiveCaller implements the ModelCaller protocol and stands in for the
live Qwen endpoint. These tests pin the live path of PilotDriver:
* same event count / final state hash as the recorded baseline when the
  fake serves the identical tape;
* verbatim capture to live_tape.jsonl (one line per call, prompt included);
* quarantined proposals are AUDITED (action unknown, blocked by
  policy:quarantine), response_raw preserved, run completes, ledger verifies;
* the default recorded path is unchanged (no live_tape written);
* live_run_meta.json never contains key material.

The REAL live run is a script-style invocation outside pytest; CI must
never make network calls (see src/verdi/pilot/live.py docstring).
"""
